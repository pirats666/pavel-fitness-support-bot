function ruGoal(value: string) {
  return ({ loss: 'похудение', mass: 'набор мышечной массы', health: 'здоровье и общая физическая форма' } as Record<string, string>)[value] ?? value;
}

function ruExperience(value: string) {
  return ({ beginner: 'новичок', under1: 'до 1 года', '1to3': '1–3 года', '3plus': '3+ года' } as Record<string, string>)[value] ?? value;
}

function ruLocation(value: string) {
  return ({ gym: 'тренажёрный зал', home: 'дом', outdoor: 'спортивная площадка/улица', mixed: 'смешанный формат' } as Record<string, string>)[value] ?? value;
}

function catalogText(exercises: AIExerciseCandidate[]) {
  return exercises.map((e) => [
    'ID=' + e.id,
    'название=' + e.nameRu,
    'зона=' + e.bodyPartRu,
    'оборудование=' + e.equipmentRu,
    'мышцы=' + e.muscleGroupRu,
    'типы=' + e.trainingTypes.join(','),
    'контексты=' + (e.trainingContexts ?? []).join(','),
    'паттерн=' + e.movementPattern,
    'уровень=' + e.level,
    'gif=' + (e.gifUrl ?? 'нет'),
    'техника=' + e.instructionsRu.slice(0, 500)
  ].join(' | ')).join('\n');
}

function canonicalMuscleGroup(e: AIExerciseCandidate): string {
  const s = (e.nameRu + ' ' + e.bodyPartRu + ' ' + e.muscleGroupRu + ' ' + e.movementPattern).toLowerCase();
  if (/икр|голен/.test(s)) return 'икры';
  if (/бицепс|сгибан.*рук/.test(s)) return 'бицепс';
  if (/трицепс|разгибан.*рук/.test(s)) return 'трицепс';
  if (/предплеч/.test(s)) return 'предплечья';
  if (/пресс|живот|кор|скруч|подъ[её]м ног/.test(s)) return 'пресс/кор';
  if (/ягод|glute|hip thrust/.test(s)) return 'ягодицы';
  if (/задн.*бедр|hamstring|сгибан.*ног/.test(s)) return 'задняя поверхность бедра';
  if (/квадриц|передн.*бедр|разгибан.*ног/.test(s)) return 'квадрицепс';
  if (/разгибател.*спин|гиперэкст/.test(s)) return 'разгибатели спины';
  if (/плеч|дельт|жим над головой|махи/.test(s)) return 'плечи';
  if (/груд|pector|жим лёжа|жим лежа|отжиман|сведен.*груд/.test(s)) return 'грудь';
  if (/спин|широч|тяга|подтяг/.test(s)) return 'спина';
  if (/кардио|бег|ходьб|велотр|эллип|степ/.test(s)) return 'кардио';
  return /cardio|кардио/.test(s) ? 'кардио' : 'спина';
}

