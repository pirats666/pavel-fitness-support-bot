export type AnatomyExercise = {
  id: string;
  name: string;
  muscleGroup: string;
  muscle: string;
  subdivision: string;
  primaryAction: string;
  environment: 'home' | 'gym' | 'outdoor';
  environmentRu: string;
  category: string;
  equipmentRu: string;
  notes: string;
};

const CATEGORY: Record<string,string> = {
  'Грудь':'chest','Спина':'back','Плечи':'shoulders','Руки':'upper arms',
  'Ноги':'upper legs','Ягодицы':'upper legs','Голень':'lower legs','Кор':'waist',
  'Плечевой пояс':'shoulders','Плечо':'shoulders'
};

function slug(value: string) {
  return value.toLowerCase().replace(/ё/g,'е')
    .replace(/[^a-zа-я0-9]+/gi,'-').replace(/^-|-$/g,'');
}

function addRow(out: AnatomyExercise[], row: string[], env: AnatomyExercise['environment']) {
  const [group,muscle,subdivision,primaryAction,home,gym,outdoor,,notes] = row;
  const source = env === 'home' ? home : env === 'gym' ? gym : outdoor;
  const environmentRu = env === 'home' ? 'Дом' : env === 'gym' ? 'Зал' : 'Спортплощадка';
  const equipmentRu = env === 'home'
    ? 'Собственный вес + безопасная мебель/опора'
    : env === 'gym'
      ? 'Свободные веса/блоки/тренажёры'
      : 'Собственный вес + турник/брусья/лавочка';

  for (const raw of source.split(';')) {
    const name = raw.trim();
    if (!name) continue;
    if (env === 'home' && /рюкзак|отягощ|гантел|штанг|гир|сопротивлен|предмет/.test(name.toLowerCase())) continue;
    const id = `anat-${env}-${slug(group)}-${slug(muscle)}-${slug(name)}`;
    out.push({
      id, name, muscleGroup: group, muscle, subdivision, primaryAction,
      environment, environmentRu, category: CATEGORY[group] ?? 'other',
      equipmentRu, notes
    });
  }
}

