function recommendedFormat(profile: AIPlannerProfile): { format: string; dayFocus: string[] } {
  const n = Math.min(Math.max(profile.workoutsPerWeek, 1), 5);
  if (profile.goal === 'mass') {
    if (n <= 2) return { format: 'Full Body — набор мышечной массы', dayFocus: ['Full Body A', 'Full Body B'] };
    if (n === 3) return {
      format: 'Сплит 3 дня — грудь + руки / спина + плечи / ноги',
      dayFocus: ['Грудь + руки', 'Спина + плечи', 'Ноги']
    };
    if (n === 4) return {
      format: 'Сплит 4 дня — грудь + трицепс / спина + бицепс / ноги / плечи + руки',
      dayFocus: ['Грудь + трицепс', 'Спина + бицепс', 'Ноги', 'Плечи + руки']
    };
    return {
      format: 'Upper / Lower 5 дней с приоритетом гипертрофии',
      dayFocus: ['Верх A', 'Низ A', 'Верх B', 'Низ B', 'Дополнительный верх']
    };
  }
  if (n <= 2) return { format: 'Full Body', dayFocus: Array.from({length:n}, (_,i)=>'Full Body ' + String.fromCharCode(65+i)) };
  if (n === 3) return { format: 'Full Body 3 дня', dayFocus: ['Full Body A','Full Body B','Full Body C'] };
  return { format: 'Upper / Lower', dayFocus: ['Верх A','Низ A','Верх B','Низ B'].slice(0,n) };
}

